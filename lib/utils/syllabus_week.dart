/// 課綱「每週進度」表裡那個週次欄的解析與顯示。
///
/// 學校的課綱頁**只有中文版** —— 介面切成英文時，週次欄拿到的仍然是 `第5週`。
/// 週次是這張表裡唯一「不是老師寫的內容、而是結構」的欄位，所以只有它由 App
/// 這側翻譯；同一列的進度內容／教學方法／備註是學校的中文原文，一律原樣顯示。
library;

/// 從學校的週次字串抽出週次數字；抽不到回 `null`。
///
/// 學校的格式固定是 `第N週`（阿拉伯數字），所以解析就是抽第一段數字。抽不到時
/// 呼叫端應原樣顯示原字串 —— 顯示看不懂的原文，好過顯示空白或一個猜出來的數字。
int? parseSyllabusWeek(String raw) {
  final match = RegExp(r'\d+').firstMatch(raw);
  if (match == null) return null;
  return int.tryParse(match.group(0)!);
}
